import { readFile, writeFile, readdir } from "node:fs/promises";
const dir = "supabase/migrations",
  files = await readdir(dir);
const read = async (suffix) =>
  readFile(`${dir}/${files.find((f) => f.endsWith(suffix))}`, "utf8");
const target = files.find((f) => f.endsWith("_slot_menu_calendar.sql"));
if (!target) throw Error("Run supabase migration new slot_menu_calendar");
const fn = (source, name) =>
  [...source.matchAll(/create (?:or replace )?function [\s\S]*?\$\$;/g)]
    .map((m) => m[0])
    .find((s) => s.includes(`function ${name}(`));
const replace = (s, a, b) => {
  if (!s.includes(a)) throw Error(`Missing migration anchor: ${a}`);
  return s.replace(a, b);
};
let command = fn(
  await read("_reusable_dishes.sql"),
  "public.catera_v1_command",
);
command = replace(
  command,
  "elsif action in('dish.save'",
  "elsif action in('category.save','menu.saveBatch','dish.save'",
);
command = replace(
  command,
  "  elsif action in('dish.save','dish.archive') then",
  `  elsif action='category.save' then
   if jsonb_typeof(a->'name') is distinct from 'string' or length(trim(a->>'name')) not between 1 and 60 then raise exception 'INVALID_INPUT';end if;
   perform 1 from v1.caterers where id=cid for update;
   if exists(select 1 from v1.dish_categories where (caterer_id is null or caterer_id=cid) and lower(name)=lower(trim(a->>'name'))) then raise exception 'CONFLICT';end if;
   insert into v1.dish_categories(caterer_id,name) values(cid,trim(a->>'name')) returning jsonb_build_object('id',id,'name',name) into r;
  elsif action in('dish.save','dish.archive') then`,
);
command = replace(
  command,
  "    if not v1.valid_dish(a->'details')",
  "    if a->'details' ? 'categoryId' then perform v1.check_category(cid,a->'details'->>'categoryId');end if;\n    if not v1.valid_dish(a->'details')",
);
command = replace(
  command,
  "   perform v1.check_dish_sources(cid,a->'offer'->'menus',p.offer->'menus');",
  "   perform v1.check_slot_categories(cid,a->'offer'->'menus');\n   perform v1.check_dish_sources(cid,a->'offer'->'menus',p.offer->'menus');",
);
const start = command.indexOf("  elsif action='menu.save' then"),
  end = command.indexOf("  elsif action='production.freeze' then", start);
if (start < 0 || end < 0) throw Error("Missing menu command branch");
command =
  command.slice(0, start) +
  `  elsif action='menu.save' then
   perform v1.save_dated_menu(cid,a);
  elsif action='menu.saveBatch' then
   r:=v1.save_menu_batch(cid,a);
` +
  command.slice(end);
let reader = fn(await read("_calendar_metadata.sql"), "public.catera_v1_read");
reader = replace(
  reader,
  " elsif resource='availability' then",
  " elsif resource='menu-month' then return v1.menu_month(u,params);\n elsif resource='availability' then",
);
reader = replace(
  reader,
  "'contentRevisions',v1.seller_content_revisions(seller_id)",
  "'categories',v1.categories(seller_id),'contentRevisions',v1.seller_content_revisions(seller_id)",
);
const legacy = fn(
  await read("_package_contents.sql"),
  "v1.valid_contents",
).replace("function v1.valid_contents(", "function v1.valid_contents_legacy(");
// Existing demo databases may already have the additive recurring-capacity wrapper.
// Update its private implementation while preserving the wrapper and its grants.
const wrapped = command
  .replace(
    "function public.catera_v1_command(",
    "function public.catera_v1_command_legacy(",
  )
  .replaceAll(
    "catera_v1_command.request_id",
    "catera_v1_command_legacy.request_id",
  );
const install = `do $install$ begin
 if to_regprocedure('public.catera_v1_command_legacy(text,jsonb,uuid)') is not null then
  execute $command$${wrapped}$command$;
 else execute $command$${command}$command$;
 end if;
end $install$;`;
await writeFile(
  `${dir}/${target}`,
  `-- Generated by scripts/compile-slot-menu-migration.mjs. Preserve immutable historical contents.\n${legacy}\n${await readFile("packages/backend/src/slot-menus.sql", "utf8")}\n${install}\n${reader}\nrevoke all on all functions in schema v1 from public,anon,authenticated;\n`,
);
