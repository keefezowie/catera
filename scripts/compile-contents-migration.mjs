// Generate the forward migration without editing any already shipped migration.
import { readFile, writeFile, readdir } from "node:fs/promises";
const dir = "supabase/migrations";
const target = (await readdir(dir)).find((f) =>
  f.endsWith("_package_contents.sql"),
);
if (!target) throw Error("Run supabase migration new package_contents first");
const core = await readFile(`${dir}/202609090003_hardening.sql`, "utf8");
const fn = (name) => {
  const f = [...core.matchAll(/create or replace function [\s\S]*?\$\$;/g)]
    .map((m) => m[0])
    .find((s) => s.startsWith(`create or replace function ${name}(`));
  if (!f) throw Error(name);
  return f;
};
let valid = fn("v1.valid_offer").replace(
  " return true;",
  " return v1.valid_contents(o,o->>'status'<>'draft');",
);
let command = fn("public.catera_v1_command");
const start = command.indexOf("  elsif action='menu.save' then");
const end = command.indexOf("  elsif action='production.freeze' then", start);
command =
  command.slice(0, start) +
  (await readFile("packages/backend/src/contents-command.sql", "utf8")) +
  command.slice(end);
command = command.replace(
  "   ident:=(a->>'id')::uuid;\n   if ident is null then insert into v1.packages",
  `   ident:=(a->>'id')::uuid;
   if ident is not null then select * into p from v1.packages where id=ident and caterer_id=cid for update;if not found then raise exception 'FORBIDDEN';end if;end if;
   if coalesce(a->'offer'->>'packageType','')='' and (ident is null or v1.contents_template(a->'offer') is distinct from v1.contents_template(p.offer)) then raise exception 'CLASSIFY_PACKAGE';end if;
   o:=(a->'offer')-'contentRevision';
   if coalesce(o->>'packageType','')<>'' then
    o:=jsonb_set(o,'{menus}',(select coalesce(jsonb_agg((m-'source')||jsonb_build_object('name',v1.contents_summary(m))),'[]') from jsonb_array_elements(o->'menus') m));
   end if;
   rev:=case when ident is null then 1 when v1.contents_template(o)=v1.contents_template(p.offer) then coalesce((p.offer->>'contentRevision')::int,0) else coalesce((select max(revision) from v1.content_revisions where package_id=ident),0)+1 end;
   a:=jsonb_set(a,'{offer}',o||jsonb_build_object('contentRevision',rev));
   if ident is null then insert into v1.packages`,
);
command = command.replace(
  "   end if;r:=jsonb_build_object('id',ident);\n  elsif action='capacity.save'",
  `   end if;
   insert into v1.content_revisions(package_id,revision,contents) values(ident,rev,v1.contents_template(a->'offer')) on conflict do nothing;
   r:=jsonb_build_object('id',ident,'contentRevision',rev);
  elsif action='capacity.save'`,
);
let read = fn("public.catera_v1_read");
const seller = read.indexOf(" elsif resource='seller' then");
read =
  read.slice(0, seller) +
  read
    .slice(seller)
    .replace(
      "'deliveries',coalesce(",
      "'contentRevisions',v1.seller_content_revisions(seller_id),'datedMenus',coalesce((select jsonb_agg(to_jsonb(m)) from v1.menus m join v1.packages p on p.id=m.package_id where p.caterer_id=seller_id and m.service_date=dt),'[]'),'deliveries',coalesce(",
    );
const delivery = fn("v1.delivery").replace(
  "v1.delivery_menu(s.package_id,d.service_date,s.snapshot->'offer'->'menus')",
  "v1.resolve_contents(s.package_id,d.service_date,s.snapshot->'offer'->'menus',coalesce((s.snapshot->'offer'->>'contentRevision')::int,0))",
);
await writeFile(
  `${dir}/${target}`,
  "-- Generated by scripts/compile-contents-migration.mjs. Forward-only; no seeds or snapshot rewrites.\n" +
    (await readFile("packages/backend/src/contents.sql", "utf8")) +
    "\n" +
    [valid, command, read, delivery].join("\n") +
    "\nrevoke all on all functions in schema v1 from public,anon,authenticated;\n",
);
