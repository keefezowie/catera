import { readFile, writeFile, readdir } from "node:fs/promises";
const dir = "supabase/migrations";
const files = await readdir(dir);
const previous = await readFile(
  `${dir}/${files.find((f) => f.endsWith("_package_contents.sql"))}`,
  "utf8",
);
const target = files.find((f) => f.endsWith("_reusable_dishes.sql"));
if (!target) throw Error("Run supabase migration new reusable_dishes");
const fn = (name) =>
  [...previous.matchAll(/create or replace function [\s\S]*?\$\$;/g)]
    .map((m) => m[0])
    .find((s) => s.startsWith(`create or replace function ${name}(`));
let valid = await readFile("packages/backend/src/offer-validation.sql", "utf8");
let command = fn("public.catera_v1_command").replace(
  "rev int;",
  "rev int;dish v1.dishes;",
);
command = command.replace(
  "elsif action in('seller.save'",
  "elsif action in('dish.save','dish.archive','seller.save'",
);
command = command.replace(
  "  elsif action='package.save' then",
  (await readFile("packages/backend/src/dishes-command.sql", "utf8")) +
    "  elsif action='package.save' then",
);
command = command.replace(
  "coalesce(a->'offer'->>'packageType','')='' and (",
  "coalesce(a->'offer'->>'packageType','')='' and a->'offer'->>'status'<>'draft' and (",
);
command = command.replace(
  "   o:=(a->'offer')-'contentRevision';",
  "   perform v1.check_dish_sources(cid,a->'offer'->'menus',p.offer->'menus');\n   o:=(a->'offer')-'contentRevision';",
);
command = command.replace(
  "   rowdata:=a->'details'||jsonb_build_object('meal',a->>'meal');",
  "   perform v1.check_dish_sources(cid,jsonb_build_array(a->'details'),coalesce((select jsonb_build_array(details) from v1.menus where package_id=p.id and content_revision=rev and service_date=(a->>'date')::date and meal=a->>'meal'),o->'menus'));\n   rowdata:=a->'details'||jsonb_build_object('meal',a->>'meal');",
);
command = command.replace(
  "(ident is null or v1.contents_template",
  "(ident is null or coalesce((p.offer->>'contentRevision')::int,0)>0 or v1.contents_template",
);
let read = fn("public.catera_v1_read");
read = read.replace(
  "'contentRevisions',v1.seller_content_revisions(seller_id)",
  "'dishes',coalesce((select jsonb_agg(v1.library_dish(d) order by d.details->>'name',d.id) from v1.dishes d where d.caterer_id=seller_id),'[]'),'contentRevisions',v1.seller_content_revisions(seller_id)",
);
await writeFile(
  `${dir}/${target}`,
  "-- Generated by compile-dishes-migration.mjs; prior migrations and snapshots are preserved.\n" +
    (await readFile("packages/backend/src/dishes.sql", "utf8")) +
    "\n" +
    [valid, command, read].join("\n") +
    "\nrevoke all on all functions in schema v1 from public,anon,authenticated;\n",
);
