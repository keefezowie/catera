import { readFile, writeFile } from "node:fs/promises";
const previous = await readFile("supabase/migrations/20260910130548_reusable_dishes.sql", "utf8");
let read = [...previous.matchAll(/create or replace function [\s\S]*?\$\$;/g)]
  .map(m => m[0]).find(s => s.startsWith("create or replace function public.catera_v1_read("));
if (!read) throw Error("READ_RPC_MISSING");
const needle = "elsif resource='customer' then\n  return jsonb_build_object(";
if (!read.includes(needle)) throw Error("CUSTOMER_BRANCH_CHANGED");
read = read.replace(needle, `elsif resource='customer' then
  return (case when params->>'calendarMeta'='true' then jsonb_build_object('calendarMeta',(
    select jsonb_build_object('nextDeliveryDate',min(d.service_date),'lastUpcomingDeliveryDate',max(d.service_date))
    from v1.delivery_days d join v1.subscriptions s on s.id=d.subscription_id
    where s.user_id=u and d.service_date >= (current_timestamp at time zone 'Asia/Jakarta')::date
      and d.status not in ('delivered','cancelled')
      and exists (select 1 from v1.fulfillments f where f.day_id=d.id and f.status not in ('delivered','cancelled'))
  )) else '{}'::jsonb end) || jsonb_build_object(`);
await writeFile("supabase/migrations/20260910160000_calendar_metadata.sql",
  "-- Additive customer calendar metadata. Generated by scripts/compile-calendar-migration.mjs.\n" + read + "\n");
